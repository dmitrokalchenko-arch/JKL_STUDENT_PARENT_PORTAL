-- Storage bucket для изображений центрального каталога техник (judo_techniques).
--
-- ПОЧЕМУ ПУБЛИЧНЫЙ, А НЕ приватный + signed URL: изображения техник (статичные
-- иллюстрации приёма, без персональных/клубных данных) не являются секретными
-- — в отличие от technique-videos/technique-images из более раннего,
-- club-scoped модуля «Прогресс техник» (см. 20260720120007_technique_progress_storage.sql),
-- где bucket приватный именно потому что видео/фото привязаны к конкретному
-- ребёнку/клубу. Здесь наоборот: один и тот же каталог из 100 техник видят
-- все клубы одинаково, персональных данных в объекте нет — публичный bucket
-- избавляет от необходимости постоянно перегенерировать signed URL с
-- истекающим сроком (что противоречило бы требованию хранить стабильный
-- image_path в judo_techniques).
--
-- Структура объектов ВНУТРИ бакета (без имени бакета как префикса):
--   techniques/<ИМЯ_ФАЙЛА_В_ВЕРХНЕМ_РЕГИСТРЕ>.png
-- Один плоский namespace 'techniques/' — локальная структура папок
-- (Tachi-Waza/5 Kyu/... и т.п.) сознательно НЕ переносится в Storage.
--
-- ЗАПИСЬ: эта миграция создаёт ТОЛЬКО сам bucket. Никаких insert/update/
-- delete policies для anon/authenticated не добавляется — загрузка 100
-- файлов выполняется один раз локальным скриптом
-- (scripts/upload-judo-technique-images.mjs) от имени service_role, который
-- RLS не подчиняется по определению. Это тот же принцип, что уже применён в
-- проекте для technique-images/technique-videos (запись — только через
-- service_role, см. комментарий в 20260720120007) — просто здесь даже
-- read-policy не нужна, потому что bucket публичный (объекты отдаются через
-- публичный URL Storage API независимо от RLS на storage.objects).
--
-- Идемпотентна: on conflict (id) do nothing — повторное применение не создаёт
-- дублей и не меняет уже существующий bucket, если он был создан вручную под
-- тем же id.

insert into storage.buckets (id, name, public)
values ('judo-techniques', 'judo-techniques', true)
on conflict (id) do nothing;
