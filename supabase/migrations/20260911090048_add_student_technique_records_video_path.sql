-- Добавляет student_video_path в public.student_technique_records — путь
-- (внутри private bucket student-technique-videos) к персональному видео
-- ВЫПОЛНЕНИЯ этой техники ЭТИМ учеником. Не путать с judo_techniques —
-- там youtube_url/youtube_video_id — эталонное референсное видео техники
-- вообще, общее для всех учеников. Это два принципиально разных видео
-- с разным жизненным циклом и разной приватностью (задание, этап 3):
--   CATALOG   -> judo_techniques.youtube_url        (публичное, эталонное)
--   COMPLETED -> student_technique_records.student_video_path (приватное,
--                конкретного ученика, конкретного выполнения)
--
-- ПОЧЕМУ NULLABLE, БЕЗ NOT NULL: старые completed records (созданные до
-- этой миграции) физически не могут иметь видео — они должны продолжать
-- работать (задание, этап 2 и 10: "старые completed records без видео
-- должны продолжать работать... video button disabled"). "Видео
-- обязательно для НОВЫХ выполнений" — это правило UI/workflow (модалка не
-- пропустит подтверждение без выбранного файла, см. фронтенд), а не
-- ограничение схемы: DB не может отличить "старую" строку от "новой" на
-- уровне constraint, а искусственный NOT NULL сломал бы уже существующие
-- строки без возможности осмысленного backfill (видео задним числом взять
-- негде).
--
-- ПОЧЕМУ ТОЛЬКО ОДНА новая колонка (не original_name/mime_type/size, хотя
-- задание допускало их "при необходимости"): mime_type и size уже
-- авторитетно хранятся в самом Storage-объекте (storage.objects.metadata)
-- — дублировать их здесь означало бы ровно то "информационное дублирование
-- с риском расхождения", которое этот проект последовательно избегает
-- (см. тот же принцип для judo_techniques полей в этой же таблице).
-- original_name не используется ни в одном экране этого этапа (модалка
-- показывает выбранный файл из локального File-объекта ДО отправки, самой
-- записи это не нужно) — добавлять поле без единого потребителя было бы
-- нарушением прямого требования задания "не добавлять лишние поля без
-- обоснования".
--
-- Путь ВНУТРИ бакета (без имени бакета как префикса) — та же конвенция,
-- что и image_path/technique-images/technique-videos в этом проекте.
alter table public.student_technique_records
  add column if not exists student_video_path text;

comment on column public.student_technique_records.student_video_path is
  'Путь ВНУТРИ private Storage bucket student-technique-videos (например "84/MUSTERMANN-KATA-GURUMA.mp4") к персональному видео ВЫПОЛНЕНИЯ этой техники этим учеником. NULL для записей без видео (старые записи ДО этой миграции — поддерживаются, video button в UI для них отключён). НЕ содержит domain/bucket/query — путь строится и проверяется тем же public.can_trainer_access_student(), что и сама эта таблица; публичного/подписанного URL здесь не хранится — signed URL строится на клиенте по требованию, коротким сроком жизни, никогда не сохраняется в БД. Никак не связано с judo_techniques.youtube_url/youtube_video_id (то — публичное референсное видео техники, общее для всех).';
