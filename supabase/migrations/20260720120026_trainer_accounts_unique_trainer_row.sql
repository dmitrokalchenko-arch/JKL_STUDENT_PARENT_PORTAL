-- НАЙДЕНО РУЧНЫМ РЕВЬЮ manage-trainer-account (пункт чеклиста "race condition
-- при параллельном создании одного аккаунта"): migration 011 сама отмечала
-- как известный пробел, что "не более одной строки trainer_accounts на
-- trainer_row_id" не обеспечено UNIQUE-ограничением, только соглашением
-- на уровне Edge Function (SELECT существующей строки перед INSERT).
--
-- Конкретный сценарий: два параллельных запроса на создание аккаунта для
-- ОДНОГО И ТОГО ЖЕ trainer_row_id, но с РАЗНЫМИ login_name (например,
-- повторная отправка формы администратором после опечатки, или два разных
-- администратора одновременно) — оба запроса видят "существующего аккаунта
-- нет" (ни один ещё не закоммичен), оба успешно создают РАЗНЫЕ auth.users
-- (разные email — коллизии email не происходит) и оба успешно вставляют
-- строку в trainer_accounts, потому что trainer_row_id ничем не ограничен.
-- Итог — два активных trainer_accounts на одного тренера, Edge Function
-- дальше работает только с "первой найденной" (см. её же комментарий),
-- что делает поведение недетерминированным.
--
-- Fix: UNIQUE(trainer_row_id) — тот же trainer_row_id не может быть в
-- trainer_accounts дважды. Второй параллельный INSERT теперь падает с
-- ошибкой unique_violation, которую Edge Function уже корректно
-- классифицирует как 409 (проверка на подстроку "duplicate" в сообщении
-- Postgres уже присутствует в коде, дополнительных изменений в Edge
-- Function не требуется).
alter table public.trainer_accounts
  add constraint trainer_accounts_trainer_row_id_key unique (trainer_row_id);
